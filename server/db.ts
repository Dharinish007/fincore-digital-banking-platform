class InMemoryDatabase {
  private state: DatabaseState;

  constructor() {
    this.state = getInitialData();
  }

  public getState(): DatabaseState {
    return this.state;
  }

  public reset(): void {
    this.state = getInitialData();
  }

  public getDashboardStats(): DashboardStats {
    const totalCustomers = this.state.customers.length;
    const totalAccounts = this.state.accounts.length;
    const totalLoans = this.state.loans.length;
    const totalTransactions = this.state.transactions.length;
    const pendingKyc = this.state.kycRecords.filter(k => k.verificationStatus === 'PENDING' || k.verificationStatus === 'UNDER_REVIEW').length;
    const activeSagas = this.state.sagas.filter(s => s.status === 'INITIATED' || s.status === 'PROCESSING' || s.status === 'COMPENSATING').length;
    const pendingRepayments = this.state.repaymentSchedules.filter(r => r.status === 'UPCOMING' || r.status === 'DUE' || r.status === 'OVERDUE').length;
    const npaLoans = this.state.npaRecords.filter(n => n.npaStatus === 'NPA').length;
    const pendingSettlements = this.state.settlements.filter(s => s.status === 'PENDING' || s.status === 'PROCESSING').length;
    const unreadNotifications = this.state.notifications.filter(n => !n.isRead).length;

    const totalDepositBalance = this.state.accounts.reduce((sum, a) => sum + (a.balance || 0), 0);
    const totalDisbursedAmount = this.state.loans.reduce((sum, l) => sum + (l.status === 'DISBURSED' ? l.principalAmount : 0), 0);
    const totalOverdueAmount = this.state.repaymentSchedules.reduce((sum, r) => sum + (r.status === 'OVERDUE' ? r.overdueAmount : 0), 0);
    const transactionVolumeToday = this.state.transactions.reduce((sum, t) => sum + t.amount, 0);

    return {
      totalCustomers,
      totalAccounts,
      totalLoans,
      totalTransactions,
      pendingKyc,
      activeSagas,
      pendingRepayments,
      npaLoans,
      pendingSettlements,
      unreadNotifications,
      totalDepositBalance,
      totalDisbursedAmount,
      totalOverdueAmount,
      transactionVolumeToday,
    };
  }
}

export const db = new InMemoryDatabase();
